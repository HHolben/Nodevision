// Native Electron acceptance tests for the editor-owned chronological HTML journal.
module.exports = async ({ win, js, key, type, delay }) => {
  const checks = [], states = [];
  const state = async label => { const value = await js('historyExperiment.state()'); states.push({ label, value }); return value; };
  const expect = async (label, text, red = false, index = 0) => {
    const value = (await state(label))[index];
    if (value.text !== text || value.element.includes('color: red') !== red) throw new Error(label + ': ' + JSON.stringify(value));
    if (!value.source.includes('lang="en"') || !value.source.includes('class="authored"') || !value.source.includes('src="example.js" defer') || /data-nv-(origin|chrome)-/.test(value.source)) throw new Error('source preservation: ' + label);
    const caretOffsets = {'native undo':1,'native redo':3,'mixed undo text':2,'mixed undo style':2,'mixed undo first run':1,'deletion run undo':3,'deletion run redo':1,'paste undo':1,'paste redo':11,'composition undo':1,'composition redo':3};
    if (label in caretOffsets && value.caret.anchorOffset !== caretOffsets[label]) throw new Error('caret restoration: '+label);
    checks.push(label);
  };
  const reset = () => js('historyExperiment.reset({instrument:false})');
  const style = () => js('historyExperiment.edit("properties")');
  const undo = () => key('Z', ['control']);
  const redo = () => key('Z', ['control', 'shift']);
  await reset(); await type('AB'); await undo(); await expect('native undo', 'x'); await redo(); await expect('native redo', 'xAB');
  await reset(); await type('A'); await style(); await type('C');
  await undo(); await expect('mixed undo text', 'xA', true);
  await undo(); await expect('mixed undo style', 'xA');
  await undo(); await expect('mixed undo first run', 'x');
  await redo(); await expect('mixed redo first run', 'xA');
  await redo(); await expect('mixed redo style', 'xA', true);
  await redo(); await expect('mixed redo last run', 'xAC', true);
  await undo(); await undo(); await type('D'); await redo(); await expect('mixed abandoned redo', 'xAD');
  await reset(); await type('A'); await key('Left'); await type('B'); await undo(); await type('D'); await redo(); await expect('native abandoned redo', 'xDA');
  await reset(); await type('A'); await js('historyExperiment.end(1)'); await type('B'); await undo(); await expect('B owns undo', 'x', false, 1); await expect('B undo preserves A', 'xA');
  await js('historyExperiment.end(0)'); win.webContents.undo(); await delay(100); await expect('menu targets A', 'x');
  win.webContents.redo(); await delay(100); await expect('menu redo A', 'xA');
  await js('document.execCommand("undo")'); await expect('script undo routes once', 'x');
  await js('document.execCommand("redo")'); await expect('script redo routes once', 'xA');
  await reset(); await type('A'); await style(); await type('C'); await undo(); await undo(); await type('D');
  await js('Document.prototype.execCommand.call(document,"redo")'); await expect('prototype native redo containment', 'xAD');
  await reset(); await type('A'); await js('historyExperiment.edit("insertion")'); await js('historyExperiment.end()'); await type('B');
  await undo(); await expect('insertion last text undo', 'xA[insert]'); await undo(); await expect('insertion undo', 'xA'); await undo(); await expect('insertion first text undo', 'x');
  await redo(); await redo(); await redo(); await expect('insertion replay', 'xA[insert]B');
  await reset(); await type('AB'); await key('Backspace'); await key('Backspace'); await undo(); await expect('deletion run undo', 'xAB'); await redo(); await expect('deletion run redo', 'x');
  const { clipboard } = require('electron'); clipboard.writeText('paste text'); win.webContents.paste(); await delay(100); await expect('paste', 'xpaste text'); await undo(); await expect('paste undo', 'x'); await redo(); await expect('paste redo', 'xpaste text');
  await reset(); win.webContents.debugger.attach('1.3');
  await win.webContents.debugger.sendCommand('Input.imeSetComposition', { text:'に', selectionStart:1, selectionEnd:1 });
  const refused = await js('(function(){try { foundation.contexts[0].setInlineStyle(foundation.contexts[0].editorElement.querySelector("#text"),"color","red"); return false; } catch { return true; }})()');
  if (!refused) throw new Error('composition did not exclude transaction');
  await win.webContents.debugger.sendCommand('Input.imeSetComposition', { text:'日本', selectionStart:2, selectionEnd:2 });
  await win.webContents.debugger.sendCommand('Input.insertText', { text:'日本' });
  await delay(100); await undo(); await expect('composition undo', 'x'); await redo(); await expect('composition redo', 'x日本');
  win.webContents.debugger.detach();
  await reset(); await type('A'); await style(); await type('C');
  win.nativeHistory.undo(); await delay(100); await expect('unadapted native menu undo', 'xA', true);
  await js('Document.prototype.execCommand.call(document,"undo")'); await expect('prototype undo uses chronology', 'xA');
  await type('D'); win.nativeHistory.redo(); await delay(100); await expect('unadapted stale redo preserves branch', 'xAD');
  await reset(); await type('A'); await js('historyExperiment.end(1)'); await type('B'); await js('historyExperiment.end(0)');
  win.nativeHistory.undo(); await delay(100); await expect('raw menu preserves B', 'xB', false, 1); await expect('raw menu owns A', 'x');
  await reset();
  await js(`foundation.contexts[0].transactions.run('table', () => {
    const table = document.createElement('table'); table.innerHTML='<tbody><tr><td>cell</td></tr></tbody>'; foundation.contexts[0].editorElement.append(table);
  })`);
  await undo(); if (await js('!!foundation.contexts[0].editorElement.querySelector("table")')) throw new Error('table undo');
  await redo(); if (!await js('!!foundation.contexts[0].editorElement.querySelector("td")')) throw new Error('table redo'); checks.push('structural table replay');
  await js(`(() => { const c=foundation.contexts[0], tx=c.transactions.begin('resize'); for(let i=0;i<20;i++) tx.preview(()=>c.editorElement.querySelector('td').style.width=i+'px'); tx.cancel(); })()`);
  if (await js('foundation.contexts[0].editorElement.querySelector("td").hasAttribute("style")')) throw new Error('resize cancellation'); checks.push('twenty preview rollback');

  await reset();
  await js(`foundation.contexts[0].transactions.run('media selection fixture', () => foundation.contexts[0].editorElement.append(document.createElement('img')))`);
  await type('A');
  await js('window.NodevisionState.activeHtmlImageContext={element:foundation.contexts[0].editorElement.querySelector("img")}');
  await undo();
  if (await js('!!window.NodevisionState.activeHtmlImageContext')) throw new Error('plain replay retained media tool context');
  await expect('plain replay clears selected media context', 'x');

  checks.push(...await require('./html-journal-structure.cjs')({win,js,key,type,delay}));
  const performance = await require('./html-journal-performance.cjs')({ win, js, type, delay });
  await reset(); await type('A'); await js('historyExperiment.end(1)'); await type('B');
  await js('window.closedHtml=foundation.contexts[0].editorElement.innerHTML; foundation.closeEditor(0); historyExperiment.end(1)');
  await undo(); if (!await js('foundation.contexts[1].editorElement.querySelector("#text").textContent === "x"')) throw new Error('closed editor ownership');
  checks.push('closing A keeps B undo isolated');
  win.nativeHistory.undo(); await delay(100);
  if (!await js('foundation.contexts[0].editorElement.innerHTML === closedHtml')) throw new Error('native history changed closed A');
  checks.push('native command cannot change closed A through B');
  return { checks, states, performance };
};
