// Nodevision/scripts/voxel-tool-browser.mjs
// This browser regression uses the production inventory, selected-item actions, voxel dialog, authoring bridge, runtime, and HTML world persistence to verify both activation routes.
import * as THREE from '/lib/three/three.module.js';
import { loadWorldFromFile } from '/PanelInstances/ViewPanels/GameViewDependencies/worldLoading.mjs';
import { saveCurrentWorldFile } from '/PanelInstances/ViewPanels/GameViewDependencies/worldSave.mjs';
import { createPlayerInventory } from '/PanelInstances/ViewPanels/GameViewDependencies/playerInventory.mjs';
import { installVoxelWorldToolAbility } from '/PanelInstances/ViewPanels/GameViewDependencies/Abilities/CraftAbilities/VoxelWorldToolAbility.mjs';
import { installSelectedItemActionAbility } from '/PanelInstances/ViewPanels/GameViewDependencies/Abilities/CommandAbilities/SelectedItemActionAbility.mjs';
import { installEditorSelectionCommandAbility } from '/PanelInstances/ViewPanels/GameViewDependencies/Abilities/CommandAbilities/EditorSelectionCommandAbility.mjs';
import { getActiveMetaWorldLayerBridge } from '/MetaWorld/MetaWorldLayerState.mjs';
import { VOXEL_WORLD_TOOL_ID, getVoxelWorldToolSettings } from '/MetaWorld/ProceduralVoxelWorld/VoxelWorldToolState.mjs';
import { createCursorFamilyProvider } from '/CursorFamilies/providers/WorldCursorProvider.mjs';
import insertVoxelWorld from '/ToolbarCallbacks/insert/insertVoxelWorld.mjs';
let checks=0;
const ok=(value,message)=>{checks++;if(!value)throw Error(message);};
try {
  window.NodevisionState={currentMode:'Virtual World Editing'};
  const panel=document.getElementById('editor'),scene=new THREE.Scene(),camera=new THREE.PerspectiveCamera(75,1.6,.1,1000);
  const state={currentWorldPath:'page.html'},movementState={playerMode:'creative',playerHeight:1.75,environment:{},isGrounded:true};
  const context=window.VRWorldContext={THREE,scene,camera,panel,state,movementState,objects:[],colliders:[],lights:[],portals:[],collisionActions:[],useTargets:[],spawnPoints:[],waterVolumes:[],measurementVisuals:[],controls:{getObject:()=>camera,unlock(){}}};
  const box={id:'authored-box',type:'box',position:[2,30,2],size:[1,1,1],color:'#ff0000',isSolid:true};
  let definition={name:'Ordinary',type:'world',worldType:'NodevisionMetaWorld',spawnPosition:{x:0,y:30,z:0},objects:[box]},savedHtml='';
  const nativeFetch=window.fetch.bind(window);
  window.fetch=async(url,options)=>{
    if(url==='/api/load-world')return {ok:true,json:async()=>({worldDefinition:structuredClone(definition)})};
    if(url==='/Notebook/page.html')return {ok:true,text:async()=>'<html><body><h1>Keep authored page</h1></body></html>'};
    if(url==='/api/save'){savedHtml=JSON.parse(options.body).content;return {ok:true,json:async()=>({success:true})};}
    return nativeFetch(url,options);
  };
  await loadWorldFromFile('page.html',state,THREE);
  const inventory=context.inventory=createPlayerInventory({panel});
  let hit={point:new THREE.Vector3(20.4,10.2,30.8)};
  const ctx={...context,api:{canUseAbility:()=>movementState.playerMode==='creative',getPlacementHit:()=>hit},selectedItemActions:new Map()};
  installSelectedItemActionAbility(ctx);installEditorSelectionCommandAbility(ctx);installVoxelWorldToolAbility(ctx);
  let bridge=getActiveMetaWorldLayerBridge();
  const form=()=>document.querySelector('[data-voxel-world-dialog]');
  const button=label=>[...form().querySelectorAll('button')].find(b=>b.textContent===label);
  const openG=()=>{movementState.selectedItemAdjustLatch=false;ctx.api.handleAdjustPress(true,performance.now());};
  const use=()=>ctx.api.handleSelectedItemAction('use',{snapToGrid:true});
  const preview=()=>scene.children.find(o=>o.name==='Voxel World placement preview');
  const original=JSON.stringify(bridge.worldData);
  ok(inventory.items.filter(i=>i.id===VOXEL_WORLD_TOOL_ID).length===1,'one inventory registration');
  ok(inventory.items.find(i=>i.id===VOXEL_WORLD_TOOL_ID).category==='tools','Tools category');
  inventory.selectDominantSlot(4);inventory.setMenuOpen(true);
  const cell=[...document.querySelectorAll('[title="Voxel World"]')].find(el=>el.querySelector('img'));
  ok(cell,'discoverable inventory cell');cell.dispatchEvent(new MouseEvent('dblclick',{bubbles:true}));inventory.setMenuOpen(false);
  ok(inventory.dominantSlots[4]===VOXEL_WORLD_TOOL_ID,'inventory assigns active slot');
  ok(inventory.getSelectedItem()?.id===VOXEL_WORLD_TOOL_ID,'hotbar equips canonical identifier');
  ok(createCursorFamilyProvider().getActiveToolId()===VOXEL_WORLD_TOOL_ID,'cursor indicator follows inventory');
  openG();ok(form(),'G adjust opens existing settings dialog');
  const seed=form().elements.seed.value;
  form().elements.sizeX.value='0';button('Apply Settings').click();
  ok(form().querySelector('[role=status]').textContent.includes('Dimensions'),'invalid values rejected');
  ok(JSON.stringify(bridge.worldData)===original,'settings never mutate scene');
  const chooseBiome=id=>{form().elements.startingBiome.value=id;form().elements.startingBiome.dispatchEvent(new Event('change',{bubbles:true}));};
  ok([...form().elements.startingBiome.options].map(o=>o.value).join(',')==='auto,aegean,temperate,snowy-pine-forest','all supported starting biomes available from G');
  form().elements.sizeX.value='32';form().elements.sizeZ.value='32';chooseBiome('aegean');
  ok(!form().querySelector('fieldset').hidden,'Aegean generation settings visible');button('Apply Settings').click();
  insertVoxelWorld();ok(form().elements.startingBiome.value==='aegean','Insert shares Aegean starting choice from G');
  chooseBiome('temperate');ok(form().querySelector('fieldset').hidden,'non-Aegean choice hides coastal-only settings');button('Apply Settings').click();
  openG();ok(form().elements.startingBiome.value==='temperate','G shares temperate starting choice from Insert');
  chooseBiome('snowy-pine-forest');
  for(const [key,value] of Object.entries({name:'Hotbar hills',seed:'shared seed',sizeX:16,sizeZ:24,minHeight:-8,maxHeight:32,loadRadius:3}))form().elements[key].value=value;
  form().elements.vegetation.checked=false;button('Apply Settings').click();
  ok(!form(),'apply closes settings');ok(JSON.stringify(bridge.worldData)===original,'apply config defers generation');
  ctx.api.updateVoxelWorldPreview({snapToGrid:true});
  ok(preview(),'placement bounds preview');ok(context.objects.every(o=>o!==preview()),'preview excluded from authored objects');
  ok(preview().box.min.toArray().join(',')==='12,2,19','preview matches snapped placement and elevation');
  inventory.selectDominantSlot(0);ok(!preview(),'switching tools disposes preview');
  inventory.selectDominantSlot(4);insertVoxelWorld();ok(form().elements.seed.value==='shared seed','toolbar shares hotbar settings');
  ok(inventory.getSelectedItem()?.id===VOXEL_WORLD_TOOL_ID,'toolbar equips same tool');
  form().elements.sizeX.value='20';button('Cancel').click();
  ok(Number(getVoxelWorldToolSettings(bridge).sizeX)===16,'cancel preserves prior configuration');
  openG();ok(form().elements.seed.value==='shared seed','G preserves text seed');button('Apply Settings').click();
  use();ok(!inventory.getSelectedItem(),'successful placement finishes tool');
  let root=context.objects.find(o=>o.userData.proceduralVoxelRuntime);
  ok(root,'canonical runtime created');ok(await root.userData.proceduralVoxelRuntime.ready,'canonical material runtime ready');
  const id=root.userData.metaWorldLayerId,placed=bridge.getVoxelWorldDefinition(id);
  ok(placed.position.join(',')==='12,10,19','placed at aimed snapped center');
  ok(placed.size.join(',')==='16,40,24' && placed.chunks.loadRadius===3,'dimensions and render settings applied');
  ok(placed.generation.vegetation===false,'generation settings applied');
  ok(placed.startingBiome==='snowy-pine-forest','starting biome stored in placed definition');
  ok(root.userData.proceduralVoxelRuntime.generator.getBiome(32,48)==='snowy-pine-forest','placement center generates the selected biome');
  ok(bridge.listObjects().length===2,'unrelated object retained');
  ok(bridge.undo(),'placement undo');ok(!context.objects.some(o=>o.userData.proceduralVoxelRuntime),'undo removes terrain');
  ok(bridge.redo(),'placement redo');root=context.objects.find(o=>o.userData.proceduralVoxelRuntime);
  ok(root.position.toArray().join(',')==='12,10,19','redo preserves placement');
  await saveCurrentWorldFile({state,movementState,objects:context.objects,lights:[]});
  ok(savedHtml.includes('Keep authored page'),'HTML persistence retains authored page');
  const saved=JSON.parse(new DOMParser().parseFromString(savedHtml,'text/html').querySelector('script').textContent);
  ok(saved.objects.filter(o=>o.type===VOXEL_WORLD_TOOL_ID).length===1,'compact canonical world serialization');
  ok(!savedHtml.includes('placement preview'),'preview never serialized');
  inventory.selectDominantSlot(4);openG();button('Apply Settings').click();use();
  ok(context.objects.filter(o=>o.userData.proceduralVoxelRuntime).length===1,'one-world restriction preserved');
  ctx.api.updateVoxelWorldPreview();window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'}));
  ok(!inventory.getSelectedItem() && !preview(),'Escape cancels placement');
  inventory.selectDominantSlot(4);ctx.api.updateVoxelWorldPreview();ctx.api.handleSelectedItemAction('attack');
  ok(!preview() && !inventory.getSelectedItem(),'attack cancels without removing authored terrain');
  inventory.selectDominantSlot(4);movementState.playerMode='survival';
  ok(insertVoxelWorld()===false,'toolbar rejected in Play');openG();ok(!form(),'G restricted in Play');use();
  ok(context.objects.filter(o=>o.userData.proceduralVoxelRuntime).length===1,'Play cannot place');
  movementState.playerMode='creative';movementState.viewPermissions={authoring:false};ok(insertVoxelWorld()===false,'read-only view blocked');delete movementState.viewPermissions;
  inventory.selectDominantSlot(7);ok(inventory.getSelectedItem()?.id==='voxel-placer','other hotbar tools retained');
  ok(inventory.dominantSlots[4]===VOXEL_WORLD_TOOL_ID,'assignment persists across tool switches');
  definition=saved;await loadWorldFromFile('page.html',state,THREE);bridge=getActiveMetaWorldLayerBridge();
  root=context.objects.find(o=>o.userData.proceduralVoxelRuntime);
  ok(root && bridge.getVoxelWorldDefinition(id).position.join(',')==='12,10,19','saved world reloads position');
  ok(bridge.getVoxelWorldDefinition(id).generator.seed===placed.generator.seed,'save/reload preserves canonical seed');
  ok(bridge.getVoxelWorldDefinition(id).startingBiome==='snowy-pine-forest','save/reload preserves chosen starting biome');
  for (let slot=1;slot<=8;slot++) {
    inventory.selectDominantSlot(slot);inventory.equipItemToActiveHand(VOXEL_WORLD_TOOL_ID);
    ok(inventory.dominantSlots[slot]===VOXEL_WORLD_TOOL_ID,'compatible hotbar slot '+(slot+1));
  }
  inventory.switchHand();inventory.equipItemToActiveHand(VOXEL_WORLD_TOOL_ID);
  ok(inventory.getActiveHand()==='off' && inventory.getSelectedItem()?.id===VOXEL_WORLD_TOOL_ID,'off-hand assignment');
  ctx.api.updateVoxelWorldPreview();inventory.dispose();ok(!preview(),'inventory disposal removes preview');
  root.userData.proceduralVoxelRuntime.dispose();
  document.getElementById('result').textContent=`PASS: ${checks} voxel tool inventory, settings, placement, restrictions, history and persistence checks`;
} catch(error) {document.getElementById('result').textContent='FAIL: '+error.stack;}
